//! CF_Als_StrideBlendAmount_{Walk,Run}.json (129 uniform samples each).
//! Input is speed in cm/s over the animated gait speed range; output
//! is the ALS StrideBlendAmount used to divide the play rate.

fn sample_curve(table: &[f32; 129], tmax: f32, speed_cm: f32) -> f32 {
    let t = (speed_cm.max(0.0) / tmax.max(1e-4)) * 128.0;
    let i = t.floor() as usize;
    if i >= 128 {
        return table[128];
    }
    let f = t - i as f32;
    table[i] * (1.0 - f) + table[i + 1] * f
}

